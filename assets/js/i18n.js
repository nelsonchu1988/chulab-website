// ===== Apply translations =====
function applyLang(lang) {
  if (!T[lang]) lang = 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (T[lang][key] !== undefined) el.innerHTML = T[lang][key];
  });
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
  // Update switcher state
  document.querySelectorAll('.lang-menu li').forEach(li => {
    li.classList.toggle('active', li.dataset.lang === lang);
  });
  const curEl = document.getElementById('cur-lang');
  if (curEl) curEl.textContent = LANGS[lang].flag + ' ' + (lang === 'en' ? 'EN' : LANGS[lang].name);
  localStorage.setItem('chulab-lang', lang);
}

// ===== Init =====
function initI18n() {
  // Build language menu
  const menu = document.getElementById('lang-menu');
  if (menu) {
    menu.innerHTML = Object.entries(LANGS).map(([code, info]) =>
      `<li data-lang="${code}" onclick="applyLang('${code}'); document.getElementById('lang-menu').classList.remove('open');">${info.flag} ${info.name}</li>`
    ).join('');
  }

  // Detect language preference
  const saved = localStorage.getItem('chulab-lang');
  const browserLang = (navigator.language || 'en').toLowerCase();
  let detected = 'en';
  if (saved && T[saved]) detected = saved;
  else if (T[browserLang]) detected = browserLang;
  else if (browserLang.startsWith('zh')) detected = browserLang.includes('tw') || browserLang.includes('hk') ? 'zh-TW' : 'zh-CN';
  else {
    const baseCode = browserLang.split('-')[0];
    if (T[baseCode]) detected = baseCode;
  }
  applyLang(detected);
}

// Toggle dropdown
function toggleLangMenu() {
  document.getElementById('lang-menu').classList.toggle('open');
}

// Close on outside click
document.addEventListener('click', e => {
  const menu = document.getElementById('lang-menu');
  const btn = document.getElementById('lang-btn');
  if (menu && !menu.contains(e.target) && !btn.contains(e.target)) menu.classList.remove('open');
});

document.addEventListener('DOMContentLoaded', initI18n);
